| ROM / RAM images of the two 6809 address spaces (generated by tools/mkimages.py into build/amiga/)
| data CPU space: only RAM $0000-$07FF and ROM $8000-$FFFF exist (the I/O window is served by accessors, $2000-$7FFF is unused):
| link.ld places the two pieces at data_mem and data_mem+$8000 and puts the program's .bss into the 30 KB hole in between.
